"""Re-cut a platform's reference locks: the lock's own packages plus ``additions.json``.

    python environments/locks/recut_locks.py --platform osx-arm64 [--write]
    python environments/locks/recut_locks.py --platform linux-64 [--write]

A reference lock is never re-solved and called the reference (README.md, "When to
re-cut"). What this tool does instead is ADD: every line of the existing explicit
conda lock is pinned exactly (``name==version=build``), every package
``additions.json`` names for the platform is pinned exactly too, and one dry-run
solve against conda-forge alone, at the lock's host floor, has to return exactly
that set: no lock package moved to another build, none dropped, and nothing added
beside the named additions. Anything else is refused by name and nothing is
written. The solve is also the closure check an explicit install never makes: the
lock then holds every package its packages depend on.

The conda lock keeps its lines byte for byte, in their order, and gains the added
packages' lines (URL and MD5 as the solve gives them) after them. The pip lock
keeps its pins byte for byte and gains each added wheel pinned by the SHA-256 that
PyPI's JSON API gives for that exact file. In both files the comment block above
the generated marker is kept as it is (it is documentation); the block below it,
the package lines and the pins are written by this tool only. Run on a lock that
already holds the additions, it reproduces the files byte for byte: that is the
check that a lock is what its inputs make (``--check``).

Options:

    --platform NAME     osx-arm64 or linux-64
    --write             write the two lock files (default: print what would change)
    --check             exit 1 unless the files equal what the inputs make
    --conda PATH        the conda executable (default: $CONDA_EXE, else conda on PATH)
    --solve-json PATH   read the solve from this file instead of running conda
    --pypi-json DIR     read PyPI's answers from DIR/<name>-<version>.json instead
                        of the network
    --save-solve PATH   keep the solve's JSON (the closure evidence) at PATH
    --lock-dir PATH     the locks directory (default: this file's directory)

The solve runs ``conda create --dry-run --json --platform <platform>
--override-channels -c conda-forge --no-default-packages --file <pins>`` with the
lock's floor as the virtual packages (``additions.json``, ``floor``), sharded
repodata on and an empty package cache of its own (``CONDA_PKGS_DIRS``), so every
package comes back with its URL and MD5 whatever the caller's cache holds. Progress
is printed, flushed, one line per stage. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import textwrap
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ADDITIONS_FILE = "additions.json"
MARKER = "# --- generated by environments/locks/recut_locks.py: do not edit below this line ---"
PLATFORMS = ("osx-arm64", "linux-64")
CHANNEL_PREFIX = "https://conda.anaconda.org/conda-forge/"
_EXPLICIT = re.compile(r"^(https://\S+/([^/#\s]+))#([0-9a-f]{32})$")
_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)\s")
PYPI_JSON = "https://pypi.org/pypi/{name}/{version}/json"


class Refused(Exception):
    """The inputs do not make a lock this tool may write; the message says why."""


def say(text: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {text}", flush=True)


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def conda_fields(filename: str):
    """``(name, version, build)`` of a conda artifact file name."""
    stem = re.sub(r"\.(conda|tar\.bz2)$", "", filename)
    if stem == filename:
        raise Refused(f"not a conda artifact file name: {filename}")
    parts = stem.rsplit("-", 2)
    if len(parts) != 3 or not all(parts):
        raise Refused(f"not a conda artifact file name: {filename}")
    return tuple(parts)


# --------------------------------------------------------------------- reading -----
def split_header(text: str):
    """``(prose lines, body lines)``: the prose ends at the marker, or at the first
    line that is not a comment when the file has no marker yet."""
    lines = text.splitlines()
    if MARKER in lines:
        index = lines.index(MARKER)
        body = lines[index + 1:]
        # the generated block is comments up to the first non-comment line
        while body and body[0].startswith("#"):
            body.pop(0)
        return lines[:index], body
    index = 0
    while index < len(lines) and lines[index].startswith("#"):
        index += 1
    prose = lines[:index]
    # a lock cut before this tool ends its prose with its own platform line
    while prose and (prose[-1].startswith("# platform:") or prose[-1] == "#"):
        prose.pop()
    return prose, lines[index:]


def read_conda_lock(text: str):
    """``(prose, entries)``: every artifact line in order, as ``{name, version, build,
    md5, url, line}``. Refuses a line that is neither a comment, ``@EXPLICIT`` nor an
    https URL with an MD5, and a name listed twice."""
    prose, body = split_header(text)
    entries, seen = [], set()
    for raw in body:
        line = raw.strip()
        if not line or line.startswith("#") or line == "@EXPLICIT":
            continue
        match = _EXPLICIT.match(line)
        if match is None:
            raise Refused(f"not an explicit lock line: {line[:120]}")
        url, filename, md5 = match.groups()
        name, version, build = conda_fields(filename)
        if name in seen:
            raise Refused(f"{name} is listed twice in the conda lock")
        seen.add(name)
        entries.append({"name": name, "version": version, "build": build, "md5": md5,
                        "url": url, "line": line})
    return prose, entries


def read_pip_lock(text: str):
    """``(prose, options, pins)``: the option lines and each pin line as ``{name,
    version, line}``, in order."""
    prose, body = split_header(text)
    options, pins, seen = [], [], set()
    for raw in body:
        line = raw.rstrip()
        if not line.strip() or line.startswith("#"):
            continue
        if line.startswith("-"):
            options.append(line)
            continue
        match = _PIN.match(line + " ")
        if match is None or "--hash=sha256:" not in line:
            raise Refused(f"not a hashed pin: {line[:120]}")
        name = normalize(match.group(1))
        if name in seen:
            raise Refused(f"{name} is pinned twice in the pip lock")
        seen.add(name)
        pins.append({"name": name, "version": match.group(2), "line": line})
    return prose, options, pins


def load_additions(lock_dir: str, platform: str) -> dict:
    with open(os.path.join(lock_dir, ADDITIONS_FILE), encoding="utf-8") as handle:
        document = json.load(handle)
    if document.get("schema") != 1:
        raise Refused(f"{ADDITIONS_FILE} has schema {document.get('schema')!r}, not 1")
    spec = (document.get("platforms") or {}).get(platform)
    if spec is None:
        raise Refused(f"{ADDITIONS_FILE} names no additions for {platform}")
    return {"conda": spec.get("conda") or [], "pypi": spec.get("pypi") or [],
            "conda_lock": spec["conda_lock"], "pip_lock": spec["pip_lock"],
            "floor": spec.get("floor") or {}}


# ----------------------------------------------------------------------- solve -----
def pins_of(entries, additions):
    """The exact specs the closure solve is given, lock first."""
    pins = [f"{entry['name']}=={entry['version']}={entry['build']}" for entry in entries]
    present = {entry["name"] for entry in entries}
    for item in additions:
        if item["name"] not in present:
            pins.append(f"{item['name']}=={item['version']}={item['build']}")
    return pins


def run_solve(conda: str, platform: str, pins, floor: dict) -> dict:
    with tempfile.TemporaryDirectory(prefix="recut_locks_") as scratch:
        spec_file = os.path.join(scratch, "pins.txt")
        with open(spec_file, "w", encoding="utf-8") as handle:
            handle.write("\n".join(pins) + "\n")
        environment = dict(os.environ)
        environment["CONDA_PLUGINS_USE_SHARDED_REPODATA"] = "true"
        # An empty package cache of the solve's own: the dry run lists under FETCH, with
        # URL and MD5, only what the cache lacks, and an addition already cached there
        # would come back without them (MEASURED 2026-10-14: libgdsii, cached, refused).
        environment["CONDA_PKGS_DIRS"] = os.path.join(scratch, "pkgs")
        for name, value in floor.items():
            environment[name] = str(value)
        argv = [conda, "create", "--dry-run", "--json", "--platform", platform,
                "-p", os.path.join(scratch, "never-created"), "--override-channels",
                "-c", "conda-forge", "--no-default-packages", "--file", spec_file]
        say(f"solving {len(pins)} exact pins for {platform} "
            f"({', '.join(f'{k}={v}' for k, v in sorted(floor.items())) or 'no overrides'})")
        done = subprocess.run(argv, capture_output=True, text=True, env=environment,
                              timeout=1800)
    try:
        solve = json.loads(done.stdout)
    except ValueError as exc:
        raise Refused(f"the solve printed no JSON (exit {done.returncode}): "
                      f"{done.stderr.strip()[-600:]}") from exc
    return solve


def judge_solve(entries, additions, solve: dict):
    """``(base, added)``: the lock's lines that are not additions, in their order, and
    the additions' ``{name, version, build, md5, url, line}`` in name order.

    Refuses unless the solve returns exactly the lock's packages and the additions:
    a lock package of another build or missing, an addition of another build, of
    another file, or missing, or any other package, each named.
    """
    if not solve.get("success"):
        raise Refused("the solve failed: " + json.dumps(solve)[:1500])
    actions = solve.get("actions") or {}
    linked = {}
    for package in actions.get("LINK") or ():
        build = package.get("build") or package.get("build_string")
        linked[package["name"]] = (package["version"], build)
    fetched = {package["name"]: package for package in actions.get("FETCH") or ()}
    findings = []
    wanted = {item["name"]: item for item in additions}
    locked = {entry["name"]: entry for entry in entries}
    for name, entry in locked.items():
        got = linked.get(name)
        if got is None:
            findings.append(f"{name} {entry['version']}={entry['build']} is in the lock "
                            "and not in the solve")
        elif got != (entry["version"], entry["build"]):
            findings.append(f"{name} moved: {entry['version']}={entry['build']} in the "
                            f"lock, {got[0]}={got[1]} in the solve")
    for name in sorted(set(linked) - set(locked) - set(wanted)):
        version, build = linked[name]
        findings.append(f"{name} {version}={build} is in the solve and is neither in "
                        f"the lock nor named in {ADDITIONS_FILE}")
    added = []
    for name, item in sorted(wanted.items()):
        got = linked.get(name)
        if got is None:
            findings.append(f"{name} {item['version']}={item['build']} is named in "
                            f"{ADDITIONS_FILE} and not in the solve")
            continue
        if got != (item["version"], item["build"]):
            findings.append(f"{name} solved to {got[0]}={got[1]}, {ADDITIONS_FILE} pins "
                            f"{item['version']}={item['build']}")
            continue
        package = fetched.get(name) or {}
        url, md5 = package.get("url"), package.get("md5")
        if not url or not md5:
            findings.append(f"{name}: the solve gives no URL and MD5 for it")
            continue
        if not url.startswith(CHANNEL_PREFIX):
            findings.append(f"{name}: {url} is not on conda-forge")
            continue
        line = f"{url}#{md5}"
        if name in locked and locked[name]["line"] != line:
            findings.append(f"{name}: the lock holds {locked[name]['line']}, the solve "
                            f"gives {line}")
            continue
        added.append({"name": name, "version": got[0], "build": got[1], "md5": md5,
                      "url": url, "line": line})
    if findings:
        raise Refused("the solve is not the lock plus its additions: " + "; ".join(findings))
    base = [entry for entry in entries if entry["name"] not in wanted]
    return base, added


# ------------------------------------------------------------------------ PyPI -----
def pypi_release(name: str, version: str, directory: str | None) -> dict:
    if directory:
        path = os.path.join(directory, f"{normalize(name)}-{version}.json")
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    url = PYPI_JSON.format(name=normalize(name), version=version)
    with urllib.request.urlopen(url, timeout=120) as response:
        return json.loads(response.read().decode("utf-8"))


def pypi_pin(item: dict, directory: str | None) -> dict:
    """``{name, version, sha256, line}`` of one added wheel, by PyPI's own digest."""
    release = pypi_release(item["name"], item["version"], directory)
    files = [entry for entry in release.get("urls") or () if entry.get("filename") == item["wheel"]]
    if len(files) != 1:
        raise Refused(f"PyPI lists {len(files)} files named {item['wheel']} for "
                      f"{item['name']} {item['version']}, not 1")
    digest = (files[0].get("digests") or {}).get("sha256")
    if not digest or not re.fullmatch(r"[0-9a-f]{64}", digest):
        raise Refused(f"PyPI gives no SHA-256 for {item['wheel']}")
    if files[0].get("yanked"):
        raise Refused(f"{item['wheel']} is yanked on PyPI")
    return {"name": normalize(item["name"]), "version": item["version"], "sha256": digest,
            "line": f"{normalize(item['name'])}=={item['version']} --hash=sha256:{digest}"}


# --------------------------------------------------------------------- writing -----
def comment(text: str, indent: str = "") -> list:
    """``text`` as comment lines of at most 90 columns."""
    return ["# " + indent + line for line in
            textwrap.wrap(text, 88 - len(indent), break_on_hyphens=False)]


def command_line(platform: str) -> str:
    return f"python environments/locks/recut_locks.py --platform {platform} --write"


def render_conda(platform: str, prose, base, added, floor) -> str:
    names = ", ".join(entry["name"] for entry in added) or "none"
    floor_text = ", ".join(f"{k}={v}" for k, v in sorted(floor.items())) or "none"
    lines = list(prose) + [MARKER]
    lines += comment(f"{len(base) + len(added)} packages: the {len(base)} lines carried over "
                     f"unchanged, then the {len(added)} that {ADDITIONS_FILE} adds ({names}).")
    lines += comment("Closure: every line pinned as name==version=build, solved with")
    lines += [f"#   conda create --dry-run --json --platform {platform} --override-channels",
              "#     -c conda-forge --no-default-packages --file <the pins>"]
    lines += comment(f"at the lock's floor ({floor_text}), returns exactly these packages: none "
                     "moved, none dropped, none beside them.")
    lines += [f"# Re-cut with:  {command_line(platform)}",
              "# Install without a solve:",
              f"#   conda create -p <prefix> --no-default-packages --file "
              f"meep-gpu-ref-{platform}.conda.txt",
              f"# platform: {platform}",
              "@EXPLICIT"]
    lines += [entry["line"] for entry in base]
    lines += [entry["line"] for entry in added]
    return "\n".join(lines) + "\n"


def render_pip(platform: str, prose, options, base, added) -> str:
    lines = list(prose) + [MARKER]
    lines += comment(f"{len(base) + len(added)} pins: the {len(base)} carried over unchanged, "
                     f"then the {len(added)} that {ADDITIONS_FILE} adds, each the one wheel it "
                     "names, by the SHA-256 PyPI's JSON API gives for that file:")
    for pin in added:
        lines.append(f"#   {pin['name']} {pin['version']}: {pin['wheel']}")
    lines.append(f"# Re-cut with:  {command_line(platform)}")
    lines += list(options)
    lines += [pin["line"] for pin in base]
    lines += [pin["line"] for pin in added]
    return "\n".join(lines) + "\n"


def recut(platform: str, lock_dir: str = HERE, conda: str | None = None,
          solve_json: str | None = None, pypi_dir: str | None = None,
          save_solve: str | None = None):
    """``{conda_path: text, pip_path: text, added_conda, added_pip}`` for one platform."""
    additions = load_additions(lock_dir, platform)
    conda_path = os.path.join(lock_dir, additions["conda_lock"])
    pip_path = os.path.join(lock_dir, additions["pip_lock"])
    with open(conda_path, encoding="utf-8") as handle:
        conda_prose, entries = read_conda_lock(handle.read())
    with open(pip_path, encoding="utf-8") as handle:
        pip_prose, options, pins = read_pip_lock(handle.read())
    say(f"{platform}: the conda lock holds {len(entries)} packages, the pip lock "
        f"{len(pins)} pins; {ADDITIONS_FILE} names {len(additions['conda'])} conda and "
        f"{len(additions['pypi'])} PyPI additions")
    if solve_json:
        with open(solve_json, encoding="utf-8") as handle:
            solve = json.load(handle)
        say(f"read the solve from {solve_json}")
    else:
        executable = conda or os.environ.get("CONDA_EXE") or shutil.which("conda")
        if not executable:
            raise Refused("no conda executable (pass --conda)")
        solve = run_solve(executable, platform, pins_of(entries, additions["conda"]),
                          additions["floor"])
        if save_solve:
            with open(save_solve, "w", encoding="utf-8") as handle:
                json.dump(solve, handle, indent=1, sort_keys=True)
            say(f"kept the solve in {save_solve}")
    base_conda, added_conda = judge_solve(entries, additions["conda"], solve)
    say(f"the solve is the lock's {len(base_conda)} packages plus {len(added_conda)} "
        f"addition(s): {', '.join(entry['name'] for entry in added_conda) or 'none'}")
    named = {normalize(item["name"]) for item in additions["pypi"]}
    present = {pin["name"]: pin for pin in pins}
    added_pip = []
    for item in additions["pypi"]:
        expected = pypi_pin(item, pypi_dir)
        expected["wheel"] = item["wheel"]
        pin = present.get(expected["name"])
        if pin is not None and pin["line"] != expected["line"]:
            raise Refused(f"{pin['name']} is pinned as {pin['line']!r}, and "
                          f"{ADDITIONS_FILE} makes {expected['line']!r}")
        added_pip.append(expected)
    base_pip = [pin for pin in pins if pin["name"] not in named]
    say(f"PyPI: {len(base_pip)} pins of the lock plus {len(added_pip)} addition(s)")
    return {conda_path: render_conda(platform, conda_prose, base_conda, added_conda,
                                     additions["floor"]),
            pip_path: render_pip(platform, pip_prose, options, base_pip, added_pip),
            "added_conda": added_conda, "added_pip": added_pip}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--platform", required=True, choices=PLATFORMS)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--conda")
    parser.add_argument("--solve-json")
    parser.add_argument("--pypi-json")
    parser.add_argument("--save-solve")
    parser.add_argument("--lock-dir", default=HERE)
    arguments = parser.parse_args(argv)
    try:
        result = recut(arguments.platform, arguments.lock_dir, arguments.conda,
                       arguments.solve_json, arguments.pypi_json, arguments.save_solve)
    except (Refused, OSError, ValueError, subprocess.SubprocessError) as exc:
        say(f"REFUSED: {exc}")
        return 1
    status = 0
    for path in sorted(key for key in result if key.endswith(".txt")):
        with open(path, encoding="utf-8") as handle:
            current = handle.read()
        same = current == result[path]
        say(f"{os.path.basename(path)}: {'unchanged' if same else 'changes'}")
        if arguments.write and not same:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(result[path])
            say(f"wrote {path}")
        if arguments.check and not same:
            status = 1
    if arguments.check:
        say("CHECK " + ("PASSED: the lock files are what their inputs make" if status == 0
                        else "FAILED: a lock file is not what its inputs make"))
    return status


if __name__ == "__main__":
    sys.exit(main())
