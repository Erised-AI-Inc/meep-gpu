def checkout_disagreements(imported: dict) -> list:
    """The files a run recorded whose bytes in this checkout differ from the record."""
    return sorted(name for name, digest in imported.items()
                  if (_API / name).is_file()
                  and hashlib.sha256((_API / name).read_bytes()).hexdigest() != digest)


def recut_device_tier(entry: dict, imported: dict, artifact_name: str) -> tuple:
    """``(device_sha256, None)`` re-cut for the run being bound, or ``(None, why)``.

    ``(None, None)`` for an entry that pins no device tier: a rebind never gives one to an
    entry that had none (that is ``mint_metal_weld.py``'s first cut, never a rebind's).

    THE VALUE IS THE CHECKOUT'S, THE EVIDENCE IS THE RUN'S. A gate artifact records the bytes
    the gate imported (``imported_source_sha256``), not the corpus digest of a module's
    emitted shaders, so the digest is recomputed here, the way ``mint_metal_weld.py``
    computes it. That is honest only where the checkout IS what the run imported: each
    pinned path must be in the run's import record at the checkout's bytes, or the entry is
    refused by name, as ``rebind_triton_welds.py`` refuses a Triton device pin. The caller
    has already refused a run that recorded any file at other bytes (``artifact_drift``),
    so the modules a pinned module imports are the run's bytes too.

    FAIL CLOSED: a pinned path for which ``device_identity`` establishes no digest on this
    checkout refuses the entry. Writing ``{}``, or dropping the pin, would move the weld to
    the comments-only code tier without anyone deciding it.
    """
    pinned = entry.get("device_sha256")
    if not pinned:
        return None, None
    if not isinstance(pinned, dict):
        return None, (f"device_sha256 is {type(pinned).__name__}, not a map of pinned paths; "
                      f"nothing re-cuts a shape this tool did not write")
    recut = {}
    for name in sorted(pinned):
        path = _API / name
        if name not in imported:
            return None, (f"device_sha256 pins {name}, which {artifact_name} does not record: "
                          f"the run did not import the module whose shaders the digest names, "
                          f"so it cannot vouch for them")
        if not path.is_file():
            return None, f"device_sha256 pins {name}, which is not in the checkout"
        if hashlib.sha256(path.read_bytes()).hexdigest() != imported[name]:
            return None, (f"device_sha256 pins {name}, whose bytes in the checkout differ from "
                          f"the ones {artifact_name} records; a digest re-cut from the checkout "
                          f"would name shaders that run never emitted")
        # ABSOLUTE, as mint_metal_weld.py passes it: ``device_digests`` decides which
        # device-source spelling applies by the path's directory, and a repo-relative
        # path resolves to kind "none".
        kind, digests = device_digests(path)
        if not digests:
            return None, (f"device_sha256 pins {name}, and device_identity establishes no "
                          f"device digest for it on this checkout; a rebind never drops a "
                          f"device pin to the code tier")
        recut[name] = {"kind": kind, "digests": digests}
    return recut, None


def _device_moves(before: dict, after: dict) -> list:
    """``(path, moved, added, removed)`` per pinned device path whose digests changed."""
    out = []
    old_tier = before.get("device_sha256") or {}
    for name, block in sorted((after.get("device_sha256") or {}).items()):
        old = (old_tier.get(name) or {}).get("digests") or {}
        new = block.get("digests") or {}
        moved = sorted(k for k in set(old) & set(new) if old[k] != new[k])
        added, removed = sorted(set(new) - set(old)), sorted(set(old) - set(new))
        if moved or added or removed:
            out.append((name, moved, added, removed))
    return out


def _unchanged_but_the_clock(before: dict, after: dict, architecture: str) -> bool:
    """True when ``after`` differs from ``before`` at most in this architecture's
    ``recorded_utc``: the rebind restated a run the ledger already holds."""
    copies = []
    for side in (before, after):
        copy = json.loads(json.dumps(side))
        run = (copy.get(metal_runs.RUNS) or {}).get(architecture)
        if isinstance(run, dict):
            run.pop("recorded_utc", None)
        copies.append(json.dumps(copy, sort_keys=True))
    return copies[0] == copies[1]


def _family_of(entry_key: str) -> str:
    """``metal_ade_update_p_device_gate`` -> ``ade_update_p``."""
    name = entry_key
    for prefix in ("metal_",):
        if name.startswith(prefix):
            name = name[len(prefix):]
    for suffix in ("_device_gate", "_gate"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    return name


def _artifact_for(family: str, stamp: str) -> Path | None:
    directory = RESULTS / f"metal_{family}_{stamp}"
    if not directory.is_dir():
        return None
    for candidate in ("gate.json", f"{family}.json", "whole_step.json"):
        if (directory / candidate).is_file():
            return directory / candidate
    found = sorted(directory.glob("*.json"))
    return found[0] if found else None


def _artifact_across(family: str, stamps) -> tuple:
    """``(artifact, stamp, stamps holding a directory)`` over every stamp given.

    The artifact and its stamp are None unless exactly one stamp holds the family's
    directory: two are a collision the caller refuses by name, and none is no artifact.
    """
    holding = [stamp for stamp in stamps if (RESULTS / f"metal_{family}_{stamp}").is_dir()]
    if len(holding) != 1:
        return None, None, holding
    return _artifact_for(family, holding[0]), holding[0], holding


#: The suffix every derived ``subnormal_policy`` line carries, as
#: ``mint_metal_weld.py`` writes it: the policy a Metal weld runs under is the table's.
POLICY_SUFFIX = metal_runs.POLICY_SUFFIX


def subnormal_policy(entry: dict, architecture: str, fresh: dict,
                     artifact_name: str) -> tuple:
    """``(policy, where it was read from)`` for this architecture's new run, or ``(None, why)``.

    THE LINE IS CARRIED, NOT RETYPED, in this order:

    1. this architecture's previous run of the gate: the curated sentences in the
       ledger are claims someone wrote about the gate, and a rebind of the same gate
       on the same GPU does not change them;
    2. the one line every other live run of the entry carries: the policy belongs to
       the table, MPS flushing float32 subnormals natively on every Apple GPU, so a
       second architecture's first run states what the first one's states, and the
       run says which architecture it was carried from;
    3. only for an entry no live run describes, the artifact's own statement, as
       ``mint_metal_weld.py`` writes it: its policy VALUE
       (``metal_runs.artifact_policy``), never the repr of a policy report.
    """
    runs = entry.get(metal_runs.RUNS) or {}
    previous = runs.get(architecture)
    if isinstance(previous, dict) and previous.get("subnormal_policy"):
        return (previous["subnormal_policy"],
                f"carried from {metal_runs.RUNS}[{architecture!r}], this "
                f"architecture's previous run of the gate")
    others = {name: run.get("subnormal_policy")
              for name, run in metal_runs.live_runs(entry).items()
              if name != architecture and run.get("subnormal_policy")}
    if len(set(others.values())) == 1:
        name = sorted(others)[0]
        return (others[name],
                f"carried from {metal_runs.RUNS}[{name!r}]: the policy is the table's "
                f"(MPS flushes float32 subnormals natively on every Apple GPU)")
    stated = metal_runs.artifact_policy(fresh)
    if stated:
        return f"{stated}{POLICY_SUFFIX}", f"derived from {artifact_name}"
    return None, (f"{artifact_name} states no subnormal policy and no other live run "
                  f"carries one line to take ({sorted(set(others.values()))})")


