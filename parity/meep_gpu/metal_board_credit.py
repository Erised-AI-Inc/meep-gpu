"""The Metal fusion board's credit rules, kept beside the composer they follow.

``build_fusion_matrix.py`` credits a seam-instance to a fused product when the
product's clause ladder admits the row AND the census records the composer selecting
the product's pair. Since series entry 18 those two stopped meaning the same thing on
the ``B_to_H`` seam, and the board's disjointness floor refused a census cut on the 1.0
frozen bytes (354 rows admitted against 322 credited). This module holds the three
rules that settle it, torch-free so the floor can be tested on any host:

THE COMPOSER-ABSORB CREDIT. The census records ``launch.plan_step`` called with
``fuse=False``. That call fills ``update_H`` from the arm table and then, AFTER the
fusion block, pops it where the run's first ``update_H`` would start H from B
(``launch.h_start_reasons``) under a base constitutive plan that does not
(``starts_h_from_b = False``). ``plan_step`` applies the start clause after the fusion
block "so a pair that absorbs the slot keeps it": with fusion on, the B/H pair takes
``update_H`` from the arm the table selected (``launch._pair_may_absorb`` against
``launch.FUSED_PAIR_ARMS``), its deposit bracket carries the start
(``deposit_repair._START_KEY``), and its plan declares no ``starts_h_from_b = False``,
so the start clause leaves the slot alone. A seam-instance whose constitutive slot the
base composer popped is therefore credited to the pair that absorbs it, and only when
every step of that rule holds on the row:

1. the census slot is unselected and every reason it records is a start-clause
   reason, recognised by the lead the composer's own ``h_start_reasons`` writes;
2. none of those reasons is one the pair's own predicate also raises (the volumes
   clause, asked by every B/H pair with an empty source list) or refuses on (an
   undeclared source list): those strings are generated by calling the composer's
   ``h_start_reasons`` on stand-in fields, never typed here;
3. exactly one wired arm's census predicate covers the slot: the arm the table
   selected before the pop (``_select_slot`` fills a slot only from a single
   admitter, and the start clause pops only a standing plan);
4. exactly one product on the seam may absorb that selection by the composer's own
   ``_pair_may_absorb`` over its ``FUSED_PAIR_ARMS`` row and declared extras, and the
   seam's pair absorbs that slot (``FUSED_PAIR_SEAMS``);
5. that product's clause ladder admits the row;
6. that product's plan does not declare ``starts_h_from_b = False``.

Every credited instance names the pair that absorbs. Nothing here lists a row.

CREDIT WITHHELD BY NAME. A row a product's predicate admits while the composer refuses
the arm the product implements is a disagreement between the two, not a credit. The
board records it in :data:`CREDIT_WITHHELD` with its reason, checks every entry against
the census on every cut (the entry refuses the cut when its disagreement is no longer
on the census), and leaves the predicate as it is for a later release to settle.

THE THREE-SEAM DISJOINTNESS FLOOR. Per product, the rows its ladder admits must be
exactly the rows credited to it plus the rows withheld from it by name. Any other row
is admitted by a product whose pair the composer does not install on it, which is a
predicate overlap, and :func:`three_seam_floor` refuses the cut naming product and row.
"""
from __future__ import annotations

import os
from types import SimpleNamespace
from typing import Any, Callable, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

__all__ = ["CREDIT_WITHHELD", "StartClause", "absorb_credit", "derive_start_clause",
           "slot_admitters", "three_seam_floor", "withheld_disagreement"]


class StartClause:
    """The composer's start-clause wording, derived from the composer itself.

    ``lead``: the prefix every reason of ``h_start_reasons`` carries.
    ``pair_refusing``: the exact reasons a B/H pair's own predicate raises too (one per
    start volume) or refuses on (the undeclared source list).
    """

    __slots__ = ("lead", "pair_refusing", "magnetic_example")

    def __init__(self, lead: str, pair_refusing: Iterable[str],
                 magnetic_example: str) -> None:
        self.lead = lead
        self.pair_refusing = frozenset(pair_refusing)
        self.magnetic_example = magnetic_example

    def is_start_reason(self, reason: str) -> bool:
        return isinstance(reason, str) and reason.startswith(self.lead)

    def pair_carries(self, reason: str) -> bool:
        """A start reason the absorbing pair's bracket carries (a magnetic deposit)."""
        return self.is_start_reason(reason) and reason not in self.pair_refusing


def derive_start_clause(h_start_reasons: Callable[..., Sequence[str]],
                        volumes: Sequence[str]) -> StartClause:
    """Ask the composer's ``h_start_reasons`` for its own wording, on stand-in fields.

    Three kinds of stand-in, each built to trip exactly one clause: no source list
    declared; one start volume holding a non-+0 word (once per name in ``volumes``,
    the composer's ``H_START_VOLUMES``); one magnetic source. Each must return exactly
    one reason, and the lead is the common prefix of the first two kinds. A reworded
    composer moves these strings with it; a composer whose clauses no longer separate
    this way refuses here rather than being matched loosely.
    """
    import numpy  # noqa: PLC0415 - only the stand-in volumes need it

    def ask(fields: Any, sources: Any) -> str:
        reasons = tuple(h_start_reasons(fields, sources))
        if len(reasons) != 1:
            raise SystemExit(
                f"launch.h_start_reasons returned {len(reasons)} reasons on a stand-in "
                f"built to trip one clause ({reasons!r}); the board cannot derive the "
                f"start clause's wording from it")
        return reasons[0]

    if not volumes:
        raise SystemExit("launch.H_START_VOLUMES is empty; the start clause's volume "
                         "reasons cannot be derived")
    undeclared = ask(SimpleNamespace(h_separated=False), None)
    by_volume = []
    for name in volumes:
        fields = SimpleNamespace(h_separated=False)
        setattr(fields, name, numpy.ones(1, dtype=numpy.float32))
        by_volume.append(ask(fields, ()))
    magnetic = ask(SimpleNamespace(h_separated=False),
                   (SimpleNamespace(field_type="B", component="Hy"),))
    lead = os.path.commonprefix([undeclared, by_volume[0]])
    every = [undeclared, magnetic] + by_volume
    if not lead.strip() or any(not reason.startswith(lead) for reason in every):
        raise SystemExit(
            f"the composer's start-clause reasons share no lead ({lead!r}); the board "
            f"cannot tell a start-clause pop from another refusal")
    refusing = [undeclared] + by_volume
    if magnetic in refusing or len(set(refusing)) != len(refusing):
        raise SystemExit(
            "the composer's start-clause reasons do not separate the magnetic-source "
            "clause from the volumes clause and the undeclared source list")
    return StartClause(lead, refusing, magnetic)


def slot_admitters(row: Mapping[str, Any], slot: str) -> List[str]:
    """The labels of the WIRED arms whose census predicate covers ``slot`` on ``row``.

    Joined on (family, slot): the census's ``arm_table`` carries each registered arm's
    family, label and wiring; its ``predicates`` carry each arm's verdict by family
    and sub-step. An unwired arm is a weld row the base table never consults.
    """
    predicates = row.get("predicates") or {}
    covered_families = {block.get("family") for block in predicates.values()
                        if block.get("sub_step") == slot and block.get("covered")}
    return [arm["label"] for arm in row.get("arm_table") or ()
            if arm.get("slot") == slot and arm.get("wired")
            and arm.get("family") in covered_families]


def absorb_credit(row: Mapping[str, Any], label: str, seam: str, curl_slot: str,
                  const_slot: str, start: StartClause,
                  seam_absorbs: Mapping[str, str],
                  candidates: Mapping[str, Sequence[Tuple[str, str]]],
                  may_absorb: Callable[[Dict[str, str], str, str, Tuple[str, str]],
                                       Optional[str]],
                  admitted: Mapping[str, Iterable[str]],
                  starts_h_from_b: Callable[[str], Optional[bool]],
                  ) -> Optional[Dict[str, Any]]:
    """The composer-absorb credit for one seam-instance, or ``None``.

    ``seam_absorbs``: curl slot -> the slot its seam's pair absorbs (the composer's
    ``FUSED_PAIR_SEAMS``). ``candidates``: the seam's products -> the arm pairs each
    may absorb (its ``FUSED_PAIR_ARMS`` row, then its declared extras). ``may_absorb``:
    the composer's ``_pair_may_absorb``. ``admitted``: product -> the rows its clause
    ladder admits. ``starts_h_from_b``: product -> what its plan declares (``None``
    where it declares nothing, which the composer reads as ``True``).

    Returns ``None`` on any row the rule does not reach. RAISES where the census
    contradicts the composer's own order: a start-clause pop on a slot that had no
    single admitter cannot have happened.
    """
    plan = row.get("plan_step") or {}
    selected = dict(plan.get("selected") or {})
    if selected.get(const_slot) is not None or seam_absorbs.get(curl_slot) != const_slot:
        return None
    reasons = list((plan.get("reasons") or {}).get(const_slot) or ())
    if not reasons or not all(start.is_start_reason(r) for r in reasons):
        return None
    if not all(start.pair_carries(r) for r in reasons):
        return None
    admitters = slot_admitters(row, const_slot)
    if len(admitters) != 1:
        raise SystemExit(
            f"{label}: the census records the start clause popping {const_slot} "
            f"({reasons[0][:120]!r}...) while {len(admitters)} wired arms cover the slot "
            f"({admitters}); the composer pops only a plan the arm table built from ONE "
            f"admitter, so the census and the composer disagree")
    arm = admitters[0]
    before = dict(selected, **{const_slot: arm})
    absorbing = [product for product, arm_pairs in candidates.items()
                 if any(may_absorb(before, curl_slot, const_slot, tuple(pair)) is None
                        for pair in arm_pairs)]
    if len(absorbing) != 1:
        return None
    product = absorbing[0]
    if label not in set(admitted.get(product, ())):
        return None
    if starts_h_from_b(product) is False:
        return None
    return {"seam": seam, "pair": product, "slot": const_slot, "arm": arm,
            "curl_arm": selected.get(curl_slot),
            "base_composer_reasons": reasons,
            "rule": ("launch.plan_step applies h_start_reasons after the fusion block, "
                     "so a pair that absorbs the slot keeps it: the base composition "
                     f"popped {const_slot} ({arm!r}) on the start clause, and {product} "
                     f"absorbs ({selected.get(curl_slot)!r}, {arm!r}) by "
                     f"_pair_may_absorb, admits the row, and carries the start in its "
                     f"deposit bracket")}


#: A product's predicate ADMITS the row and the composer REFUSES the arm the product
#: implements at that slot. Keyed by (census label, seam). Each entry names the
#: product, the slot, the arm the product implements there and its census predicate
#: key, the curl arm the composer selects, the reason, and where it was measured.
#: :func:`withheld_disagreement` re-reads every entry off the census on every cut.
#:
#: EMPTY. The one 1.0 entry (``tests:TestHoleyWvgBands.test_fields_at_kx`` at
#: ``D_to_E``, withheld from ``folded_complex_offdiag_fused_electric_pair``) was not a
#: predicate/composer disagreement but a census artifact: the census asked the composer
#: with no chunk division, the composer read the one-rank division while the arms read
#: the run's own presence through the lifted one, and on this row the two records
#: differ by one row. Each composer now resolves no division to the one the fields
#: carry, the census selects ``update_E`` there, and the entry would refuse the cut as
#: stale. Measured on that row with the product dispatched: 0 of 11,712,000 words
#: differ from the array path on the Apple GPU (flush) and on CUDA (keep).
CREDIT_WITHHELD: Dict[Tuple[str, str], Dict[str, str]] = {}


def withheld_disagreement(row: Mapping[str, Any], label: str, seam: str,
                          curl_slot: str, entry: Mapping[str, str],
                          product_pair: Optional[Tuple[str, str]],
                          admitted: Iterable[str]) -> Dict[str, Any]:
    """Check one :data:`CREDIT_WITHHELD` entry against its census row; RAISE if stale.

    The entry stands only while the census still shows the disagreement it records:
    the composer selects the named curl arm and leaves the named slot unselected,
    the named arm's census predicate covers the slot, the named product's pair is
    (curl arm, arm), and the product's clause ladder admits the row.
    """
    plan = row.get("plan_step") or {}
    selected = plan.get("selected") or {}
    predicate = (row.get("predicates") or {}).get(entry["predicate_key"]) or {}
    problems = []
    if product_pair != (entry["curl_arm"], entry["arm"]):
        problems.append(f"the product's pair is {product_pair}, not "
                        f"({entry['curl_arm']!r}, {entry['arm']!r})")
    if selected.get(curl_slot) != entry["curl_arm"]:
        problems.append(f"{curl_slot} selects {selected.get(curl_slot)!r}, not "
                        f"{entry['curl_arm']!r}")
    if selected.get(entry["slot"]) is not None:
        problems.append(f"{entry['slot']} now selects {selected.get(entry['slot'])!r}: "
                        f"the composer no longer refuses the arm")
    if not predicate.get("covered") or predicate.get("sub_step") != entry["slot"]:
        problems.append(f"{entry['predicate_key']} does not cover {entry['slot']} on "
                        f"the census")
    if label not in set(admitted):
        problems.append(f"{entry['product']}'s clause ladder no longer admits the row")
    if problems:
        raise SystemExit(
            f"{label} @ {seam}: the credit withheld from {entry['product']} by name no "
            f"longer stands on this census ({'; '.join(problems)}). Retire or re-earn "
            f"the CREDIT_WITHHELD entry; a withheld credit whose disagreement is gone "
            f"is a stale label")
    return {"product": entry["product"], "slot": entry["slot"], "arm": entry["arm"],
            "reason": entry["reason"], "evidence": entry["evidence"],
            "composer_reasons_on_the_census": list(
                (plan.get("reasons") or {}).get(entry["slot"]) or ())}


def three_seam_floor(ladder_rows: Mapping[str, Iterable[str]],
                     instances: Iterable[Mapping[str, Any]]) -> Dict[str, Any]:
    """Per product: the rows its ladder admits == credited rows + rows withheld by name.

    ``ladder_rows``: every three-seam product -> the rows its clause ladder admits.
    ``instances``: one per three-seam seam-instance, with ``row``, ``product`` (the
    product credited, or ``None``), ``served`` and ``credit_withheld`` (``None`` or a
    block naming ``product``); an absorb-credited instance also carries ``absorbed``
    naming its pair, which must be its ``product``.

    RAISES on any row admitted by a product and neither credited to it nor withheld
    from it by name (a predicate overlap: the product admits a row whose pair the
    composer does not install), on any credit to a product whose ladder refuses the
    row, and on a row both credited and withheld. Returns the summary block.
    """
    credited: Dict[str, set] = {}
    withheld: Dict[str, set] = {}
    absorbed: Dict[str, set] = {}
    for item in instances:
        if item.get("served"):
            credited.setdefault(item["product"], set()).add(item["row"])
            block = item.get("absorbed")
            if block is not None:
                if block.get("pair") != item["product"]:
                    raise SystemExit(
                        f"{item['row']}: an absorb credit names {block.get('pair')!r} "
                        f"and the instance is credited to {item['product']!r}")
                absorbed.setdefault(item["product"], set()).add(item["row"])
        held = item.get("credit_withheld")
        if held is not None:
            withheld.setdefault(held["product"], set()).add(item["row"])
    ladders = {product: set(rows) for product, rows in ladder_rows.items()}
    overlap, unadmitted, both = {}, {}, {}
    for product in sorted(set(ladders) | set(credited) | set(withheld)):
        admits = ladders.get(product, set())
        took = credited.get(product, set())
        held = withheld.get(product, set())
        if took & held:
            both[product] = sorted(took & held)
        if (took | held) - admits:
            unadmitted[product] = sorted((took | held) - admits)
        if admits - took - held:
            overlap[product] = sorted(admits - took - held)
    admitted_total = sum(len(rows) for rows in ladders.values())
    credited_total = sum(len(rows) for rows in credited.values())
    withheld_total = sum(len(rows) for rows in withheld.values())
    absorbed_total = sum(len(rows) for rows in absorbed.values())
    if overlap or unadmitted or both:
        raise SystemExit(
            f"the three-seam clause ladders admit {admitted_total} rows but only "
            f"{credited_total} seam-instances credit a product and {withheld_total} are "
            f"withheld by name: some row is admitted by a product whose pair plan_step "
            f"does not select and that no absorbing pair keeps, so the arm predicates "
            f"are no longer disjoint and this matrix cannot be trusted. Admitted, "
            f"neither credited nor withheld: {overlap}; credited or withheld without "
            f"admission: {unadmitted}; both credited and withheld: {both}")
    return {
        "clause_ladder_admitted": admitted_total,
        "credited": credited_total,
        "credited_by_the_selected_pair": credited_total - absorbed_total,
        "credited_by_an_absorbing_pair": absorbed_total,
        "credit_withheld_by_name": withheld_total,
        "absorb_credits_by_pair": {p: len(r) for p, r in sorted(absorbed.items())},
        "withheld_by_product": {p: sorted(r) for p, r in sorted(withheld.items())},
        "agree": True,
        "what_it_proves": (
            "per product, the rows its clause ladder admits are exactly the rows "
            "credited to it (the census's selected pair, or the pair that absorbs the "
            "slot the base composer popped) plus the rows withheld from it by name"),
    }
