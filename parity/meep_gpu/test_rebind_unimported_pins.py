@pytest.mark.parametrize("table", sorted(TOOLS))
def test_every_generated_row_is_in_the_tool_table(table, generated):
    rows = TOOLS[table].RETIRED_UNIMPORTED_PINS
    missing = {row: gates for row, gates in generated[table].items() if row not in rows}
    assert not missing, (f"{table}: rows the generator produces and the table lacks; print them "
                         f"with `import_closure.py unimported-pins {table}`, review, add: {missing}")
    wrong = {row: (rows[row], gates) for row, gates in generated[table].items()
             if tuple(rows[row]) != tuple(gates)}
    assert not wrong, f"{table}: rows naming another gate than the generator: {wrong}"


@pytest.mark.parametrize("table", sorted(TOOLS))
def test_every_table_row_is_generated_or_already_retired_and_still_holds(table, generated,
                                                                         ledgers, resolver):
    """The other direction, valid on both sides of the bind: a row the generator no longer
    produces must belong to a weld that is in the ledger and no longer pins the file (the
    bind dropped it), and the rule must still hold for it on this checkout."""
    rows = TOOLS[table].RETIRED_UNIMPORTED_PINS
    ledger = ledgers[table]
    for (key, name), gates in rows.items():
        assert isinstance(ledger.get(key), dict), f"{table}: {key} is not in the ledger: a dead row"
        if (key, name) in generated[table]:
            continue
        assert name not in (ledger[key].get("source_sha256") or {}), (
            f"{table}: {key} still pins {name} and the generator does not retire it")
        assert tuple(gates) == ic.weld_gate_scripts(table, key, ledger[key]), (table, key)
    assert ic.unimported_pins_back(rows, REPO, resolver) == []


