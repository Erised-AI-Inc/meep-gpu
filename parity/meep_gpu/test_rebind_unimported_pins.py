def test_deliberate_pins_outside_a_gate_closure_are_kept(ledgers, resolver):
    """A weld's own test file and a kernel module its gate loads by computed name lie
    outside the static run closure too; they are claims, not import-record artefacts, so no
    row retires them. Measured on the shipped Triton ledger."""
    eager = ic.eager_root_modules(REPO)
    kept = []
    for key, entry in ledgers["triton"].items():
        gates = ic.weld_gate_scripts("triton", key, entry)
        held = ic.gates_run_closure(resolver, gates)
        if held is None:
            continue
        for name in entry["source_sha256"]:
            if name not in held and name not in eager and (REPO / name).is_file():
                kept.append((key, name))
                assert (key, name) not in RT.RETIRED_UNIMPORTED_PINS
    names = {name.rsplit("/", 1)[-1] for _key, name in kept}
    assert {"offdiag_fused_electric_pair.py", "folded_offdiag_fused_electric_pair.py"} <= names
    assert sum(1 for name in names if name.startswith("test_")) >= 8, sorted(names)


def test_no_kernel_weld_outside_the_declared_gates_pins_the_planner_or_the_driver(ledgers,
                                                                                  resolver):
    """R17's direct consequence, read on the curated pins once the rows apply: a weld that
    still pins fastpath.py or driver.py names a DECLARED dispatch, route, composition or
    driver gate whose run closure holds the file (``import_closure.py bill FILE``)."""
    for table, ledger in ledgers.items():
        rows = TOOLS[table].RETIRED_UNIMPORTED_PINS
        for key, entry in ledger.items():
            gates = ic.weld_gate_scripts(table, key, entry)
            if not gates:
                continue
            for name in DISPATCH_FILES:
                if name not in entry["source_sha256"] or (key, name) in rows:
                    continue
                declared = [gate for gate in gates
                            if gate_closure.DECLARED.get(gate.rsplit("/", 1)[-1])]
                assert declared, (f"{table}: {key} pins {name} and none of its gates {gates} "
                                  f"is declared in test_gate_import_closure.DECLARED")
                assert any(name in resolver.run_closure(gate) for gate in declared), (
                    table, key, name, declared)


