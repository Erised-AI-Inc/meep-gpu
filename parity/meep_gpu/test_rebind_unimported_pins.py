HARNESS_TABLE = (
    "def helper():\n"
    "    from meep_gpu import driver\n"
    "    return driver\n"
    "def builder():\n"
    "    from meep_gpu import driver\n"
    "    return driver\n"
    "def other():\n"
    "    return 1\n"
    "TABLE = (('row', lambda: helper(), {'k': 1}), ('row2', builder, ()))\n")


def _closure_tree(root: pathlib.Path, gate: str, harness: str = HARNESS_TABLE) -> ic.Resolver:
    for rel, text in (("meep_gpu/__init__.py", '_SUBMODULES = frozenset(("driver",))\n'),
                      ("meep_gpu/driver.py", "D = 1\n"),
                      ("parity/meep_gpu/planted_matrix.py", harness),
                      ("parity/meep_gpu/gate_metal_planted.py", gate)):
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text, encoding="utf-8")
    return ic.Resolver(root)


@pytest.mark.parametrize("gate, reaches", [
    # A gate that imports the harness and never names its table: the table's lambda and
    # its stored function do not run.
    ("import planted_matrix as matrix\ndef main():\n    return matrix.other()\n", False),
    # Naming the table through the module alias reaches both entries.
    ("import planted_matrix as matrix\ndef main():\n    return [r[1]() for r in matrix.TABLE]\n", True),
    # So does a from-import of the table.
    ("from planted_matrix import TABLE\ndef main():\n    return TABLE[0][1]()\n", True),
    # Calling the stored function by name reaches it as before.
    ("import planted_matrix as matrix\ndef main():\n    return matrix.builder()\n", True),
], ids=["table-never-named", "table-named-by-alias", "table-from-imported", "entry-called-by-name"])
def test_a_table_entry_is_reached_only_where_reached_code_names_the_table(tmp_path, gate, reaches):
    resolver = _closure_tree(tmp_path, gate)
    held = "meep_gpu/driver.py" in resolver.run_closure("parity/meep_gpu/gate_metal_planted.py")
    assert held is reaches


@pytest.mark.parametrize("harness", [
    # A lambda passed to a call at module level may run at import: kept.
    HARNESS_TABLE + "REGISTERED = list(map(lambda f: f(), [helper]))\n",
    # The harness's own module-level code naming the table reaches its entries.
    HARNESS_TABLE + "NAMES = [row[0] for row in TABLE]\n",
    # A lambda under anything but a display stays with its statement.
    "def helper():\n    from meep_gpu import driver\n    return driver\n"
    "def other():\n    return 1\n"
    "TABLE = dict(row=lambda: helper())\n",
], ids=["lambda-passed-to-a-call", "table-named-at-module-level", "lambda-under-a-call"])
def test_an_entry_that_may_run_at_import_stays_in_the_closure(tmp_path, harness):
    resolver = _closure_tree(tmp_path, "import planted_matrix as matrix\n"
                                       "def main():\n    return matrix.other()\n", harness)
    assert "meep_gpu/driver.py" in resolver.run_closure("parity/meep_gpu/gate_metal_planted.py")


def test_the_import_closure_does_not_move(tmp_path):
    """The refinement is the run closure's; the import closure already skipped module-level
    lambdas, and a stored function was never run by importing its table."""
    resolver = _closure_tree(tmp_path, "import planted_matrix as matrix\n")
    assert resolver.import_closure("parity/meep_gpu/gate_metal_planted.py") == {
        "parity/meep_gpu/planted_matrix.py", "parity/meep_gpu/gate_metal_planted.py"}


