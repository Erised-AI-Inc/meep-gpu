"""A curated pin the old eager package root left behind leaves its weld by a generated row.

WHAT THIS HOLDS (owner ruling R17, bit_parity_0_10 DESIGN.md sections 8 and 8.1). While the
package root imported its 23 submodules eagerly, every gate's import record held the driver,
the dispatch planner and the MEEP lift, and some welds' curated pin sets were cut from those
records. The root now binds its names on first use, so those gates' records no longer hold
the files, and the rebind tools keep curated sets: without a rule such a weld is skipped by
the Metal tool ("artifact does not record") or kept coupled to the driver by the Triton tool
(which fills an unrecorded pin from the checkout). Each tool carries
``RETIRED_UNIMPORTED_PINS``, a reviewed literal generated by
``import_closure.unimported_pins``: a pin is retired only when the file is a module of the
old eager root AND lies outside the run closure of the weld's gate.

These tests hold:

* each tool's literal to the generator, both ways: every generated row is in the table, and
  every table row the generator no longer produces belongs to a weld rebound without the
  file already, for which the rule still holds (so the table stays valid across the bind);
* the rows name only eager-root modules, never a weld's own test file, a fixture or a
  kernel module; the deliberate pins outside a gate's run closure on the shipped ledgers
  (eight Triton welds' own test files, the stencil-weld gate's two kernel modules, which it
  loads by computed name) are kept;
* after the rows apply, no kernel weld outside the declared dispatch, route, composition
  and driver gates (``test_gate_import_closure.DECLARED``) pins ``fastpath.py`` or
  ``driver.py``, and every weld that still pins one names a gate whose run closure holds it;
* the generator on planted ledgers and trees, and the run closure it reads: a harness
  table's stored lambdas and functions are reached only where reached code names the table
  (``metal_composition_matrix.MATRIX`` put ``dispersion.py`` in 22 gates' closures that never
  name it), while an entry that may run at import stays in the closure;
* the rule through each tool's ``main()`` on planted repository roots: a rebind drops a row's
  pin from both digest maps and reports ``RETIRED-PIN (not imported by <gate>)``; an artifact
  that records the file again refuses the entry; a row whose file is back in its gate's run
  closure refuses the run and writes nothing; a run that disagrees with the checkout refuses
  the entry; a non-retired missing pin still refuses; a deliberate test-file pin is
  untouched; an entry that does not rebind keeps its pin; a second ``--write`` retires
  nothing more (and leaves the Metal ledger byte-identical).

Host-only: no GPU, no MEEP. The real ledgers are read, never written.
"""

