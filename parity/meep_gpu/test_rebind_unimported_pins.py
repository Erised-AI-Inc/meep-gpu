def _plant_tree(root: pathlib.Path, gate_source: str) -> None:
    files = {
        "meep_gpu/__init__.py": '_SUBMODULES = frozenset(("driver", "grid"))\n',
        "meep_gpu/driver.py": "DRIVER = 1\n",
        "meep_gpu/grid.py": "GRID = 1\n",
        "meep_gpu/test_planted.py": "T = 1\n",
        "meep_gpu/metal_kernels/__init__.py": "",
        "meep_gpu/metal_kernels/planted.py": "K = 1\n",
        "parity/meep_gpu/gate_metal_planted.py": gate_source,
    }
    for rel, text in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text, encoding="utf-8")


PLANTED_PINS = ("meep_gpu/driver.py", "meep_gpu/grid.py", "meep_gpu/test_planted.py",
                "meep_gpu/metal_kernels/planted.py", "parity/meep_gpu/gate_metal_planted.py")


def _planted_ledger() -> dict:
    return {"metal_planted_device_gate": {"source_sha256": {n: "e" * 64 for n in PLANTED_PINS}},
            "driver_dispatch": {"source_sha256": {"meep_gpu/driver.py": "e" * 64}},
            "metal_gateless_device_gate": {"source_sha256": {"meep_gpu/driver.py": "e" * 64}}}


